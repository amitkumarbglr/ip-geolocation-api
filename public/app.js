// Demo UI. Uses only the public API, so it doubles as a client example.
const $ = (id) => document.getElementById(id);
const els = {
  form: $('lookup-form'),
  input: $('ip-input'),
  btn: $('lookup-btn'),
  me: $('me-btn'),
  status: $('status'),
  result: $('result'),
  explainBtn: $('explain-btn'),
  explain: $('r-explain'),
};

let current = null;

const setStatus = (msg, isError = false) => {
  els.status.textContent = msg;
  els.status.classList.toggle('error', isError);
};

const text = (id, value) => {
  $(id).textContent = value ?? '—';
};

async function getJson(url, options) {
  const res = await fetch(url, options);
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(body.error?.message ?? `Request failed (${res.status})`);
  return body;
}

function render(r) {
  current = r;
  const loc = r.location;
  text('r-ip', r.ip);
  text('r-flag', loc?.flag ?? '');
  text('r-city', loc?.city);
  text('r-region', loc?.region);
  text('r-country', loc?.country);
  text('r-coords', loc?.latitude != null ? `${loc.latitude.toFixed(4)}, ${loc.longitude.toFixed(4)}` : null);
  text('r-tz', loc?.timezone);
  text('r-currency', loc?.currency);
  text('r-org', r.connection.org);
  text('r-asn', r.connection.asn);

  const acc = r.accuracy;
  const label = $('r-accuracy-label');
  label.textContent = acc.level === 'none' ? 'not available' : `${acc.level} · ${acc.score}/100`;
  label.className = `pill ${acc.level}`;
  $('r-accuracy-bar').style.width = `${acc.score}%`;
  $('r-notes').replaceChildren(...acc.notes.map((n) => {
    const li = document.createElement('li');
    li.textContent = n;
    return li;
  }));

  const flags = $('r-flags');
  flags.replaceChildren(...['vpn', 'proxy', 'mobile', 'hosting'].filter((k) => k in r.connection.flags).map((k) => {
    const chip = document.createElement('span');
    chip.className = `chip${r.connection.flags[k] ? ' on' : ''}`;
    chip.textContent = `${k}: ${r.connection.flags[k] ? 'yes' : 'no'}`;
    return chip;
  }));

  const map = $('r-map');
  if (loc?.latitude != null) {
    map.href = `https://www.openstreetmap.org/?mlat=${loc.latitude}&mlon=${loc.longitude}#map=8/${loc.latitude}/${loc.longitude}`;
    map.hidden = false;
  } else {
    map.hidden = true;
  }

  els.explain.hidden = true;
  els.explain.textContent = '';
  els.result.hidden = false;
}

async function lookup(ip) {
  els.btn.disabled = true;
  setStatus('Looking up…');
  try {
    const data = await getJson(`/api/v1/ip/${encodeURIComponent(ip)}`);
    render(data);
    setStatus(data.meta.cached ? 'Served from cache.' : `Looked up via ${data.meta.provider ?? 'n/a'}.`);
  } catch (err) {
    els.result.hidden = true;
    setStatus(err.message, true);
  } finally {
    els.btn.disabled = false;
  }
}

els.form.addEventListener('submit', (e) => {
  e.preventDefault();
  const ip = els.input.value.trim();
  if (ip) lookup(ip);
});

els.me.addEventListener('click', async () => {
  els.input.value = '';
  await lookup('me');
  if (current) els.input.value = current.ip;
});

els.explainBtn.addEventListener('click', async () => {
  if (!current) return;
  els.explainBtn.disabled = true;
  try {
    const { explanation } = await getJson(`/api/v1/ip/${encodeURIComponent(current.ip)}/explain`, { method: 'POST' });
    els.explain.textContent = explanation.text;
    const note = document.createElement('small');
    note.textContent = explanation.source === 'model'
      ? `Generated by ${explanation.model}.`
      : `Template explanation${explanation.reason ? ` (${explanation.reason})` : ''}.`;
    els.explain.append(note);
    els.explain.hidden = false;
  } catch (err) {
    setStatus(err.message, true);
  } finally {
    els.explainBtn.disabled = false;
  }
});

// Pre-fill from ?ip= so results can be linked.
const params = new URLSearchParams(location.search);
if (params.get('ip')) {
  els.input.value = params.get('ip');
  lookup(params.get('ip'));
}
